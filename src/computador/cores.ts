const bloco = (cores: Cores) =>
  Object.entries(cores)
    .map(([nome, valor]) => `--mac-${nome}:${valor};`)
    .join("");

/**
 * As variáveis do computador nos dois temas: o claro na raiz dele, o escuro com o data-theme do blog. O
 * `.mac-fora` é a caixa do Terminal suspenso por cima do blog, fora do computador.
 */
export function cssDasCores(): string {
  return `:is(.mac,.mac-fora){${bloco(claro)}color-scheme:light}:root[data-theme="dark"] :is(.mac,.mac-fora){${bloco(escuro)}color-scheme:dark}`;
}
